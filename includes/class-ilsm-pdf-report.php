<?php
/**
 * Lightweight dependency-free PDF report generator.
 *
 * Uses PDF built-in Helvetica fonts and vector drawing commands only.
 * No remote resources, user supplied SVG, JavaScript, or executable content is embedded.
 */
if ( ! defined( 'ABSPATH' ) ) { exit; }

class ILSM_PDF_Report {
    private $pages = array();
    private $content = '';
    private $page_width = 595.28;
    private $page_height = 841.89;
    private $margin = 34;
    private $y = 800;
    private $page_no = 0;
    private $footer_label = 'DMA InternLink Mapper';
    private $images = array();
    private $page_images = array();
    private $brand_logo_cache = null;
    private $site_logo_cache = null;
    private $site_name_cache = null;

    public function __construct( $footer_label = '' ) {
        if ( $footer_label ) { $this->footer_label = (string) $footer_label; }
        $this->new_page();
    }

    public function page_width() { return $this->page_width; }
    public function page_height() { return $this->page_height; }
    public function margin() { return $this->margin; }
    public function current_y() { return $this->y; }
    public function page_number() { return $this->page_no; }

    public function new_page() {
        if ( '' !== $this->content ) { $this->pages[] = $this->content; }
        $this->content = '';
        $this->page_no++;
        $this->y = $this->page_height - $this->margin;
        $this->footer();
    }

    private function footer() {
        $this->line( $this->margin, 31, $this->page_width - $this->margin, 31, 226, 232, 240, 0.45 );
        $this->set_color( 71, 85, 105 );
        $site_name = $this->site_name();
        $this->text( $this->margin, 18, $this->shorten( $site_name, 46 ), 7.2, true );
        $this->set_color( 148, 163, 184 );
        $this->text( 210, 18, __( 'Generated by DMA InternLink Mapper', 'dma-internlink-mapper' ), 6.7 );
        $this->text( $this->page_width - 82, 18, 'Page ' . $this->page_no, 7.2 );
    }

    private function esc( $text ) {
        $text = html_entity_decode( wp_strip_all_tags( (string) $text ), ENT_QUOTES | ENT_HTML5, 'UTF-8' );
        $text = preg_replace( '/[^\x20-\x7E]/', '', $text );
        return str_replace( array( '\\', '(', ')', "\r", "\n" ), array( '\\\\', '\\(', '\\)', ' ', ' ' ), $text );
    }

    public function set_color( $r, $g, $b, $stroke = false ) {
        $this->content .= sprintf( "%.3F %.3F %.3F %s\n", $r / 255, $g / 255, $b / 255, $stroke ? 'RG' : 'rg' );
    }

    public function text( $x, $y, $text, $size = 10, $bold = false ) {
        $font = $bold ? 'F2' : 'F1';
        $this->content .= sprintf( "BT /%s %.2F Tf %.2F %.2F Td (%s) Tj ET\n", $font, $size, $x, $y, $this->esc( $text ) );
    }

    public function rect( $x, $y, $w, $h, $r = 255, $g = 255, $b = 255, $stroke = null ) {
        $this->set_color( $r, $g, $b );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F re f\n", $x, $y, $w, $h );
        if ( is_array( $stroke ) ) {
            $this->set_color( $stroke[0], $stroke[1], $stroke[2], true );
            $this->content .= sprintf( "%.2F %.2F %.2F %.2F re S\n", $x, $y, $w, $h );
        }
    }

    public function rounded_rect( $x, $y, $w, $h, $radius = 8, $fill = array(255,255,255), $stroke = array(226,232,240) ) {
        $r = min( (float) $radius, $w / 2, $h / 2 ); $k = 0.5522847498; $c = $r * $k;
        $path = sprintf( "%.2F %.2F m ", $x + $r, $y );
        $path .= sprintf( "%.2F %.2F l %.2F %.2F %.2F %.2F %.2F %.2F c ", $x + $w - $r, $y, $x + $w - $r + $c, $y, $x + $w, $y + $r - $c, $x + $w, $y + $r );
        $path .= sprintf( "%.2F %.2F l %.2F %.2F %.2F %.2F %.2F %.2F c ", $x + $w, $y + $h - $r, $x + $w, $y + $h - $r + $c, $x + $w - $r + $c, $y + $h, $x + $w - $r, $y + $h );
        $path .= sprintf( "%.2F %.2F l %.2F %.2F %.2F %.2F %.2F %.2F c ", $x + $r, $y + $h, $x + $r - $c, $y + $h, $x, $y + $h - $r + $c, $x, $y + $h - $r );
        $path .= sprintf( "%.2F %.2F l %.2F %.2F %.2F %.2F %.2F %.2F c h ", $x, $y + $r, $x, $y + $r - $c, $x + $r - $c, $y, $x + $r, $y );
        if ( is_array( $fill ) ) { $this->set_color( $fill[0],$fill[1],$fill[2] ); $this->content .= $path . "f\n"; }
        if ( is_array( $stroke ) ) { $this->set_color( $stroke[0],$stroke[1],$stroke[2], true ); $this->content .= "0.65 w " . $path . "S\n"; }
    }

    public function line( $x1, $y1, $x2, $y2, $r = 203, $g = 213, $b = 225, $width = 1 ) {
        $this->set_color( $r, $g, $b, true );
        $this->content .= sprintf( "%.2F w %.2F %.2F m %.2F %.2F l S\n", $width, $x1, $y1, $x2, $y2 );
    }

    public function circle( $cx, $cy, $radius, $r, $g, $b, $width = 8 ) {
        $k = 0.5522847498; $c = $radius * $k;
        $this->set_color( $r, $g, $b, true );
        $this->content .= sprintf( "%.2F w %.2F %.2F m ", $width, $cx + $radius, $cy );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c ", $cx + $radius, $cy + $c, $cx + $c, $cy + $radius, $cx, $cy + $radius );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c ", $cx - $c, $cy + $radius, $cx - $radius, $cy + $c, $cx - $radius, $cy );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c ", $cx - $radius, $cy - $c, $cx - $c, $cy - $radius, $cx, $cy - $radius );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c S\n", $cx + $c, $cy - $radius, $cx + $radius, $cy - $c, $cx + $radius, $cy );
    }

    /**
     * Embed a JPEG image on the current page.
     *
     * @param string $jpeg Binary JPEG data.
     * @param int    $pixel_width JPEG pixel width.
     * @param int    $pixel_height JPEG pixel height.
     * @param float  $x PDF x coordinate.
     * @param float  $y PDF y coordinate.
     * @param float  $width Rendered width.
     * @param float  $height Rendered height.
     * @return bool
     */
    public function jpeg_image( $jpeg, $pixel_width, $pixel_height, $x, $y, $width, $height ) {
        if ( ! is_string( $jpeg ) || '' === $jpeg || $pixel_width < 1 || $pixel_height < 1 || $width <= 0 || $height <= 0 ) {
            return false;
        }

        $image_index = count( $this->images ) + 1;
        $name = 'Im' . $image_index;
        $this->images[ $image_index ] = array(
            'name'   => $name,
            'data'   => $jpeg,
            'width'  => (int) $pixel_width,
            'height' => (int) $pixel_height,
        );
        if ( ! isset( $this->page_images[ $this->page_no ] ) ) {
            $this->page_images[ $this->page_no ] = array();
        }
        $this->page_images[ $this->page_no ][] = $image_index;
        $this->content .= sprintf( "q %.2F 0 0 %.2F %.2F %.2F cm /%s Do Q\n", $width, $height, $x, $y, $name );
        return true;
    }

    public function filled_circle( $cx, $cy, $radius, $r, $g, $b ) {
        $k = 0.5522847498; $c = $radius * $k;
        $this->set_color( $r, $g, $b );
        $this->content .= sprintf( "%.2F %.2F m ", $cx + $radius, $cy );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c ", $cx + $radius, $cy + $c, $cx + $c, $cy + $radius, $cx, $cy + $radius );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c ", $cx - $c, $cy + $radius, $cx - $radius, $cy + $c, $cx - $radius, $cy );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c ", $cx - $radius, $cy - $c, $cx - $c, $cy - $radius, $cx, $cy - $radius );
        $this->content .= sprintf( "%.2F %.2F %.2F %.2F %.2F %.2F c f\n", $cx + $c, $cy - $radius, $cx + $radius, $cy - $c, $cx + $radius, $cy );
    }

    public function progress_ring( $cx, $cy, $radius, $percent, $size = 15 ) {
        $percent = max( 0, min( 100, (int) $percent ) );
        $this->circle( $cx, $cy, $radius, 226, 232, 240, 6 );
        $color = $percent >= 90 ? array(22,163,74) : ( $percent >= 70 ? array(217,119,6) : ( $percent >= 50 ? array(234,88,12) : array(220,38,38) ) );
        $segments = max( 1, (int) round( 64 * $percent / 100 ) );
        $this->set_color( $color[0], $color[1], $color[2], true );
        $this->content .= "6 w 1 J\n";
        for ( $i=0; $i<$segments; $i++ ) {
            $a1 = deg2rad( 90 - ( $i * 360 / 64 ) );
            $a2 = deg2rad( 90 - ( ( $i + 0.82 ) * 360 / 64 ) );
            $x1=$cx+$radius*cos($a1); $y1=$cy+$radius*sin($a1); $x2=$cx+$radius*cos($a2); $y2=$cy+$radius*sin($a2);
            $this->content .= sprintf( "%.2F %.2F m %.2F %.2F l S\n", $x1,$y1,$x2,$y2 );
        }
        $this->set_color( 15,23,42 );
        $label=(string)$percent; $offset = strlen($label)>=3 ? 11 : 7;
        $this->text( $cx-$offset, $cy-5, $label, $size, true );
        $this->set_color( 100,116,139 ); $this->text( $cx-9, $cy-17, '/100', 6.5 );
    }

    public function wrapped_text( $x, $y, $text, $max_chars = 75, $size = 9, $line_height = 13, $bold = false, $max_lines = 0 ) {
        $words = preg_split( '/\s+/', trim( $this->esc( $text ) ) ); $lines=array(); $line='';
        foreach ( $words as $word ) { $candidate = '' === $line ? $word : $line . ' ' . $word; if ( strlen($candidate)>$max_chars && ''!==$line ) { $lines[]=$line; $line=$word; } else { $line=$candidate; } }
        if ( ''!==$line ) { $lines[]=$line; }
        if ( $max_lines && count($lines)>$max_lines ) { $lines=array_slice($lines,0,$max_lines); $lines[$max_lines-1]=rtrim($lines[$max_lines-1],'. ').'...'; }
        foreach ( $lines as $i=>$line_text ) { $this->text($x,$y-($i*$line_height),$line_text,$size,$bold); }
        return $y-(count($lines)*$line_height);
    }

    public function set_y( $y ) { $this->y=(float)$y; }
    public function ensure_space( $height ) { if ( $this->y-$height < 48 ) { $this->new_page(); return true; } return false; }

    /**
     * Return the current site's display name for report branding.
     *
     * @return string
     */
    private function site_name() {
        if ( null !== $this->site_name_cache ) {
            return $this->site_name_cache;
        }
        $name = function_exists( 'get_bloginfo' ) ? (string) get_bloginfo( 'name' ) : '';
        $name = trim( wp_strip_all_tags( $name ) );
        $this->site_name_cache = '' !== $name ? $name : $this->footer_label;
        return $this->site_name_cache;
    }

    /**
     * Convert a local attachment image to a small JPEG for the PDF engine.
     *
     * @param string $source Local file path.
     * @return array|false
     */
    private function local_image_as_jpeg( $source ) {
        if ( ! is_string( $source ) || '' === $source || ! is_readable( $source ) || ! function_exists( 'wp_get_image_editor' ) ) {
            return false;
        }
        $editor = wp_get_image_editor( $source );
        if ( is_wp_error( $editor ) ) {
            return false;
        }
        $size = $editor->get_size();
        if ( is_array( $size ) && ( (int) $size['width'] > 240 || (int) $size['height'] > 240 ) ) {
            $editor->resize( 240, 240, false );
        }
        $tmp = wp_tempnam( 'ilsm-pdf-site-logo.jpg' );
        if ( ! $tmp ) {
            return false;
        }
        $saved = $editor->save( $tmp, 'image/jpeg' );
        if ( is_wp_error( $saved ) || empty( $saved['path'] ) || ! is_readable( $saved['path'] ) ) {
            if ( file_exists( $tmp ) ) { wp_delete_file( $tmp ); }
            return false;
        }
        $data = file_get_contents( $saved['path'] ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local temporary image generated by WordPress.
        $info = false !== $data ? @getimagesizefromstring( $data ) : false; // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- Invalid image conversion is handled by the fallback.
        wp_delete_file( $saved['path'] );
        if ( $saved['path'] !== $tmp && file_exists( $tmp ) ) {
            wp_delete_file( $tmp );
        }
        if ( ! is_string( $data ) || ! is_array( $info ) || IMAGETYPE_JPEG !== (int) $info[2] ) {
            return false;
        }
        return array( 'data' => $data, 'width' => (int) $info[0], 'height' => (int) $info[1] );
    }

    /**
     * Return the website logo (custom logo first, site icon second) as JPEG.
     * Falls back to the bundled plugin icon only when the site has no usable logo.
     *
     * @return array|false
     */
    private function site_logo_jpeg() {
        if ( null !== $this->site_logo_cache ) {
            return $this->site_logo_cache;
        }
        $this->site_logo_cache = false;
        $attachment_ids = array();
        if ( function_exists( 'get_theme_mod' ) ) {
            $custom_logo = absint( get_theme_mod( 'custom_logo', 0 ) );
            if ( $custom_logo ) { $attachment_ids[] = $custom_logo; }
        }
        $site_icon = absint( get_option( 'site_icon', 0 ) );
        if ( $site_icon ) { $attachment_ids[] = $site_icon; }
        foreach ( array_unique( $attachment_ids ) as $attachment_id ) {
            $path = get_attached_file( $attachment_id );
            $jpeg = $this->local_image_as_jpeg( $path );
            if ( $jpeg ) {
                $this->site_logo_cache = $jpeg;
                return $this->site_logo_cache;
            }
        }
        $this->site_logo_cache = $this->brand_logo_jpeg();
        return $this->site_logo_cache;
    }

    /**
     * Return the bundled plugin icon as a JPEG suitable for the lightweight PDF engine.
     *
     * The source remains admin/images/icon-40.png. Conversion is performed locally
     * through WordPress' image editor and cached only for this request.
     *
     * @return array|false Array with data, width and height, or false on failure.
     */
    private function brand_logo_jpeg() {
        if ( null !== $this->brand_logo_cache ) {
            return $this->brand_logo_cache;
        }

        $this->brand_logo_cache = false;
        if ( ! defined( 'ILSM_PATH' ) || ! function_exists( 'wp_get_image_editor' ) || ! function_exists( 'wp_tempnam' ) ) {
            return false;
        }

        $source = ILSM_PATH . 'admin/images/icon-40.png';
        if ( ! is_readable( $source ) ) {
            return false;
        }

        $editor = wp_get_image_editor( $source );
        if ( is_wp_error( $editor ) ) {
            return false;
        }

        $tmp = wp_tempnam( 'ilsm-pdf-logo.jpg' );
        if ( ! $tmp ) {
            return false;
        }

        $saved = $editor->save( $tmp, 'image/jpeg' );
        if ( is_wp_error( $saved ) || empty( $saved['path'] ) || ! is_readable( $saved['path'] ) ) {
            if ( file_exists( $tmp ) ) { wp_delete_file( $tmp ); }
            return false;
        }

        $data = file_get_contents( $saved['path'] ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local plugin-generated temporary image, no remote request.
        $info = false !== $data ? @getimagesizefromstring( $data ) : false; // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- Invalid conversion is handled by the fallback icon.
        wp_delete_file( $saved['path'] );
        if ( $saved['path'] !== $tmp && file_exists( $tmp ) ) {
            wp_delete_file( $tmp );
        }

        if ( ! is_string( $data ) || ! is_array( $info ) || IMAGETYPE_JPEG !== (int) $info[2] ) {
            return false;
        }

        $this->brand_logo_cache = array(
            'data'   => $data,
            'width'  => (int) $info[0],
            'height' => (int) $info[1],
        );
        return $this->brand_logo_cache;
    }


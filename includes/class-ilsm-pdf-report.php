    public function output( $filename ) {
        if ( '' !== $this->content ) { $this->pages[] = $this->content; }

        $objects = array();
        $objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
        $objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
        $objects[4] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>';

        $next_object = 5;
        $image_objects = array();
        foreach ( $this->images as $image_index => $image ) {
            $image_objects[ $image_index ] = $next_object;
            $objects[ $next_object ] = '<< /Type /XObject /Subtype /Image /Width ' . (int) $image['width'] . ' /Height ' . (int) $image['height'] . ' /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ' . strlen( $image['data'] ) . ">>\nstream\n" . $image['data'] . "\nendstream";
            $next_object++;
        }

        $page_objects = array();
        foreach ( $this->pages as $page_index => $stream ) {
            $page_number = $page_index + 1;
            $page_object = $next_object++;
            $content_object = $next_object++;
            $page_objects[] = $page_object . ' 0 R';

            $xobjects = '';
            if ( ! empty( $this->page_images[ $page_number ] ) ) {
                $refs = array();
                foreach ( $this->page_images[ $page_number ] as $image_index ) {
                    if ( isset( $image_objects[ $image_index ], $this->images[ $image_index ] ) ) {
                        $refs[] = '/' . $this->images[ $image_index ]['name'] . ' ' . $image_objects[ $image_index ] . ' 0 R';
                    }
                }
                if ( $refs ) { $xobjects = ' /XObject << ' . implode( ' ', $refs ) . ' >>'; }
            }

            $objects[ $page_object ] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ' . $this->page_width . ' ' . $this->page_height . '] /Resources << /Font << /F1 3 0 R /F2 4 0 R >>' . $xobjects . ' >> /Contents ' . $content_object . ' 0 R >>';
            $objects[ $content_object ] = '<< /Length ' . strlen( $stream ) . ">>\nstream\n" . $stream . "endstream";
        }
        $objects[2] = '<< /Type /Pages /Kids [' . implode( ' ', $page_objects ) . '] /Count ' . count( $this->pages ) . ' >>';
        ksort( $objects, SORT_NUMERIC );

        $out = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
        $offsets = array( 0 => 0 );
        $max_object = max( array_keys( $objects ) );
        for ( $i = 1; $i <= $max_object; $i++ ) {
            if ( ! isset( $objects[ $i ] ) ) { continue; }
            $offsets[ $i ] = strlen( $out );
            $out .= $i . " 0 obj\n" . $objects[ $i ] . "\nendobj\n";
        }
        $xref = strlen( $out );
        $out .= "xref\n0 " . ( $max_object + 1 ) . "\n0000000000 65535 f \n";
        for ( $i = 1; $i <= $max_object; $i++ ) {
            $out .= isset( $offsets[ $i ] ) ? sprintf( "%010d 00000 n \n", $offsets[ $i ] ) : "0000000000 00000 f \n";
        }
        $out .= 'trailer << /Size ' . ( $max_object + 1 ) . " /Root 1 0 R >>\nstartxref\n" . $xref . "\n%%EOF";
        nocache_headers();
        header( 'Content-Type: application/pdf' );
        header( 'Content-Disposition: attachment; filename="' . sanitize_file_name( $filename ) . '"' );
        header( 'Content-Length: ' . strlen( $out ) );
        echo $out; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Binary PDF output.
        exit;
    }

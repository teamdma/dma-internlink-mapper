    public function donut_chart( $cx, $cy, $radius, $segments, $center_top = '', $center_bottom = '' ) {
        $total = 0;
        foreach ( $segments as $seg ) { $total += max( 0, (float) $seg[0] ); }
        if ( $total <= 0 ) { $segments = array( array( 1, array( 226, 232, 240 ), 'None' ) ); $total = 1; }
        $this->circle( $cx, $cy, $radius, 226, 232, 240, 13 );
        $start = 90.0;
        foreach ( $segments as $seg ) {
            $value = max( 0, (float) $seg[0] );
            if ( $value <= 0 ) { continue; }
            $color = $seg[1];
            $steps = max( 1, (int) round( 96 * $value / $total ) );
            $this->set_color( $color[0], $color[1], $color[2], true );
            $this->content .= "13 w 1 J\n";
            for ( $i = 0; $i < $steps; $i++ ) {
                $a1 = deg2rad( $start - ( $i * 360 / 96 ) );
                $a2 = deg2rad( $start - ( ( $i + 0.82 ) * 360 / 96 ) );
                $x1 = $cx + $radius * cos( $a1 ); $y1 = $cy + $radius * sin( $a1 );
                $x2 = $cx + $radius * cos( $a2 ); $y2 = $cy + $radius * sin( $a2 );
                $this->content .= sprintf( "%.2F %.2F m %.2F %.2F l S\n", $x1, $y1, $x2, $y2 );
            }
            $start -= 360 * $value / $total;
        }
        if ( $center_top ) { $this->set_color( 15, 23, 42 ); $this->text( $cx - ( strlen( $center_top ) * 3.4 ), $cy + 2, $center_top, 13, true ); }
        if ( $center_bottom ) { $this->set_color( 71, 85, 105 ); $this->text( $cx - ( strlen( $center_bottom ) * 2.3 ), $cy - 14, $center_bottom, 6.2, true ); }
    }


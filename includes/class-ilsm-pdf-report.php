    private function table_header( $headers, $widths, $font_size ) {
        $row_height=22; $x=$this->margin; $this->rect($x,$this->y-$row_height,array_sum($widths),$row_height,15,39,71);
        $this->set_color(255,255,255); foreach($headers as $i=>$header){$this->text($x+5,$this->y-14,$header,max(6.2,$font_size),true);$x+=$widths[$i];}

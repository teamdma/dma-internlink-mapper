    }

    public function table( $headers, $rows, $widths, $font_size = 7.2 ) {
        $row_height=22; $this->ensure_space($row_height*2); $this->table_header($headers,$widths,$font_size);
        foreach($rows as $row_index=>$row){
            if($this->y-$row_height<45){$this->new_page();$this->table_header($headers,$widths,$font_size);}
            $x=$this->margin; $bg=0===$row_index%2?array(248,250,252):array(255,255,255); $this->rect($x,$this->y-$row_height,array_sum($widths),$row_height,$bg[0],$bg[1],$bg[2]);
            $this->set_color(30,41,59);
            foreach($headers as $i=>$unused){$value=isset($row[$i])?(string)$row[$i]:'';$max=max(5,(int)floor($widths[$i]/($font_size*.49)));if(strlen($value)>$max){$value=substr($value,0,max(1,$max-3)).'...';}$this->text($x+5,$this->y-14,$value,$font_size);$x+=$widths[$i];}
            $this->line($this->margin,$this->y-$row_height,$this->margin+array_sum($widths),$this->y-$row_height,226,232,240,.35); $this->y-=$row_height;
        }
        $this->y-=10;
    }

    public function graph_snapshot( $nodes, $edges, $x, $y, $w, $h, $selected_id = 0 ) {
        $this->rounded_rect($x,$y,$w,$h,8,array(250,252,255),array(226,232,240));
        if(!$nodes){$this->set_color(100,116,139);$this->text($x+16,$y+$h/2,'No internal graph data in this scan.',8);return;}
        $cx=$x+$w/2;$cy=$y+$h/2;$count=count($nodes);$positions=array();
